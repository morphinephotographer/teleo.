export const dictionaries = { en, uk, ru };
export type Locale = keyof typeof dictionaries;
export function detectLocale(
  languages: readonly string[],
  manual?: string | null,
): Locale {
  if (manual && manual in dictionaries) return manual as Locale;
  for (const l of languages) {
    const code = l.toLowerCase().split("-")[0];
    if (code in dictionaries) return code as Locale;
  }
  return "en";
}
export function localGet(key: string) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}
export function localSet(key: string, value: string) {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* Session state still works. */
  }
}
